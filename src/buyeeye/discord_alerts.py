from __future__ import annotations

import multiprocessing
import os
import time
from typing import Any

import httpx

DISCORD_TIMEOUT = httpx.Timeout(connect=5.0, read=10.0, write=10.0, pool=5.0)
DISCORD_MAX_ATTEMPTS = 2
DISCORD_TOTAL_TIMEOUT = 15.0


def _webhooks() -> dict[str, str]:
    env = os.environ
    return {
        "buyouts": env.get("DISCORD_WEBHOOK_BUYOUTS", "").strip(),
        "ending": env.get("DISCORD_WEBHOOK_ENDING", "").strip(),
        "grails": env.get("DISCORD_WEBHOOK_GRAILS", "").strip(),
        "silver": env.get("DISCORD_WEBHOOK_SILVER", "").strip(),
        "review": env.get("DISCORD_WEBHOOK_REVIEW", "").strip(),
    }


def _post_webhook(url: str, payload: dict[str, Any], result_pipe: Any) -> None:
    try:
        for attempt in range(DISCORD_MAX_ATTEMPTS):
            response = httpx.post(url, json=payload, timeout=DISCORD_TIMEOUT)
            if response.is_success:
                result_pipe.send((True, response.status_code))
                return
            if response.status_code < 500 and response.status_code != 429:
                result_pipe.send((False, response.status_code))
                return
        result_pipe.send((False, f"http_{response.status_code}"))
    except (httpx.TimeoutException, TimeoutError):
        result_pipe.send((False, "timeout"))
    except httpx.TransportError:
        result_pipe.send((False, "transport_error"))
    except httpx.HTTPError:
        result_pipe.send((False, "http_error"))


def _send_webhook(url: str, payload: dict[str, Any]) -> tuple[bool, int | str, float]:
    started = time.monotonic()
    parent_pipe, child_pipe = multiprocessing.Pipe(duplex=False)
    process = multiprocessing.Process(target=_post_webhook, args=(url, payload, child_pipe))
    process.start()
    process.join(DISCORD_TOTAL_TIMEOUT)
    if process.is_alive():
        process.terminate()
        process.join(2.0)
        result = (False, "timeout")
    elif parent_pipe.poll():
        result = parent_pipe.recv()
    else:
        result = (False, "worker_error")
    parent_pipe.close()
    child_pipe.close()
    return result[0], result[1], time.monotonic() - started


def send_test_alert() -> int:
    webhooks = _webhooks()
    configured = [name for name, url in webhooks.items() if url]
    if not configured:
        print(
            "No Discord webhooks configured. Set DISCORD_WEBHOOK_* in your environment before sending real alerts."
        )
        return 1

    payload = {
        "content": "BuyEye live test alert",
        "embeds": [
            {
                "title": "Number (N)ine - test alert",
                "description": "This is a real live alert payload generated by the current BuyEye environment.",
                "url": "https://buyee.jp/item/jdirectitems/auction/s1242650927",
                "color": 5814783,
                "fields": [
                    {"name": "Price", "value": "3,300 YEN", "inline": True},
                    {"name": "Time remaining", "value": "6 day(s)", "inline": True},
                    {
                        "name": "Reason",
                        "value": "Live parser + DB path is active; this is a test delivery only.",
                        "inline": False,
                    },
                ],
            }
        ],
    }

    sent = 0
    for name, url in webhooks.items():
        if not url:
            continue
        success, result, elapsed = _send_webhook(url, payload)
        if success:
            sent += 1
            print(
                f"Discord alert: channel={name} attempted success status={result} elapsed={elapsed:.2f}s"
            )
        else:
            print(
                f"Discord alert: channel={name} attempted failure error={result} elapsed={elapsed:.2f}s"
            )
    return 0 if sent else 1


def send_listing_alert(
    listing: Any, route: str, reason: str, score: int
) -> tuple[bool, int | str, float]:
    url = _webhooks().get(route, "")
    if not url:
        return False, "route_unconfigured", 0.0
    title = listing.title_original or "Untitled Buyee listing"
    fields = [
        {
            "name": "Price",
            "value": f"{listing.current_price:,} YEN" if listing.current_price else "unknown",
            "inline": True,
        },
        {"name": "Time remaining", "value": listing.time_remaining or "unknown", "inline": True},
        {"name": "Score", "value": str(score), "inline": True},
        {
            "name": "Brand / category",
            "value": f"{listing.brand or 'unknown'} / {listing.category or 'unknown'}",
            "inline": False,
        },
        {"name": "Reason", "value": reason, "inline": False},
    ]
    payload: dict[str, Any] = {
        "content": f"BuyEye live listing [{route}]",
        "embeds": [{"title": title, "url": listing.url, "fields": fields, "color": 5814783}],
    }
    if listing.image_url:
        payload["embeds"][0]["thumbnail"] = {"url": listing.image_url}
    return _send_webhook(url, payload)
